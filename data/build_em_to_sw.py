def _lcs(a, b):
    if not a or not b:
        return 0
    dp = [[0] * (len(b) + 1) for _ in range(len(a) + 1)]
    for i in range(1, len(a) + 1):
        for j in range(1, len(b) + 1):
            dp[i][j] = dp[i - 1][j - 1] + 1 if a[i - 1] == b[j - 1] else max(dp[i - 1][j], dp[i][j - 1])
    return dp[len(a)][len(b)]


def _core(s):
    s = re.sub(r"[ⅡⅢI\s]", "", str(s))
    s = s.replace("行业", "").replace("产业", "").replace("板块", "").replace("Ⅲ", "")
    return s


def em_to_sw(em_name):
    if not em_name:
        return None
    r = resolve_sector(em_name)[0]
    if r:
        return r
    emc = _core(em_name)
    r = resolve_sector(emc)[0]
    if r:
        return r
    for sw_name, kws in KEYWORDS:
        code = SW_NAME_TO_CODE.get(sw_name)
        if not code:
            continue
        for kw in kws:
            if kw and kw in em_name:
                return code
    best, best_len = None, 1
    for sw_name, _ in KEYWORDS:
        code = SW_NAME_TO_CODE.get(sw_name)
        if not code:
            continue
        ln = _lcs(emc, _core(sw_name))
        if ln > best_len:
            best, best_len = code, ln
    return best


def main():
    UA = {"User-Agent": "Mozilla/5.0", "Referer": "https://quote.eastmoney.com/"}
    def get(u):
        return json.loads(urllib.request.urlopen(urllib.request.Request(u, headers=UA), timeout=25).read().decode("utf-8", "ignore"))
    boards = []
    pn = 1
    while True:
        d = get(("https://push2.eastmoney.com/api/qt/clist/get?pn=%d&pz=100&fs=m:90+t:2&fields=f12,f14" % pn)).get("data") or {}
        diff = d.get("diff")
        rows = list(diff.values()) if isinstance(diff, dict) else (diff or [])
        if not rows:
            break
        boards += [str(r.get("f14") or "").strip() for r in rows if r.get("f14")]
        if len(rows) < 100:
            break
        pn += 1
        time.sleep(0.1)
    bridge = {}
    miss = []
    for b in boards:
        c = em_to_sw(b)
        if c:
            bridge[b] = c
        else:
            miss.append(b)
    with open(OUT, "w", encoding="utf-8") as f:
        json.dump(bridge, f, ensure_ascii=False, indent=1)
    print("桥接命中:", len(bridge), "/", len(boards), " 残余:", len(miss))
    if miss:
        print("残余:", miss)


if __name__ == "__main__":
    main()
